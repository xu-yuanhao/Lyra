// Direct media is base64-encoded into the provider JSON body. Keep the raw
// payload bounded so encoding cannot turn one attachment into an 80+ MiB
// request. Larger-provider upload APIs are separate transports and must not be
// simulated by raising this inline limit.
const MAX_DIRECT_MEDIA_BYTES: u64 = 20 * 1024 * 1024;

pub(super) fn provider_messages_from_agent_message(
    message: &Value,
    message_index: usize,
    all_messages: &[Value],
    options: &ProviderContextOptions,
    output: &mut ProviderContext,
) -> Vec<Value> {
    let Some(role) = message.get("role").and_then(Value::as_str) else {
        return Vec::new();
    };
    if excludes_provider_context(message) {
        return Vec::new();
    }
    if role == "assistant"
        && let Some(messages) = provider_protocol_v2_messages(message, message_index, options)
    {
        return messages;
    }
    let text = message
        .get("text")
        .and_then(Value::as_str)
        .unwrap_or_default();

    // Compressed-context-block: role=system message produced by memory_compress.
    // Wrap its JSON payload with a framing prefix so the provider treats it as a
    // summary of prior conversation, not a generic system instruction.
    if role == "system"
        && message.pointer("/metadata/kind").and_then(Value::as_str)
            == Some("compressed-context-block")
    {
        if text.trim().is_empty() {
            return Vec::new();
        }
        return vec![json!({
            "role": "system",
            "content": format!(
                "The following is a compressed context summary of earlier conversation in this session, generated by Lyra. Treat it as authoritative context about prior exchanges; prefer newer messages for current intent.\n\n{text}"
            ),
        })];
    }

    if role == "system"
        && message.pointer("/metadata/kind").and_then(Value::as_str) == Some("subagent-completion")
    {
        if text.trim().is_empty() {
            return Vec::new();
        }
        return vec![json!({
            "role": "system",
            "content": text,
        })];
    }

    if role == "tool" {
        let (content, evidence_ref) = trim_tool_output(
            text,
            effective_tool_output_budget(options, message.get("id")),
            message.get("id"),
        );
        if let Some(evidence_ref) = evidence_ref {
            output.evidence_refs.push(evidence_ref);
        }
        return if content.trim().is_empty() {
            Vec::new()
        } else {
            let mut tool_message = json!({
                "role": "tool",
                "tool_call_id": message.get("toolCallId").or_else(|| message.get("tool_call_id")).cloned().unwrap_or_else(|| Value::String("tool-result".to_string())),
                "content": content,
            });
            if let Some(name) = message
                .get("name")
                .and_then(Value::as_str)
                .filter(|name| !name.is_empty())
            {
                tool_message["name"] = json!(name);
            }
            vec![tool_message]
        };
    }

    // Legacy tool UI blocks are not an executable protocol. Keep the durable
    // assistant prose; complete V2 calls/results are projected separately.
    if role == "assistant"
        && message
            .get("blocks")
            .and_then(Value::as_array)
            .is_some_and(|blocks| {
                blocks
                    .iter()
                    .any(|b| b.get("type").and_then(Value::as_str) == Some("tool"))
            })
    {
        return text_content_or_none(text)
            .map(|content| vec![json!({"role":"assistant", "content": content})])
            .unwrap_or_default();
    }

    let mut projected = Vec::new();
    let blocks = message
        .get("blocks")
        .and_then(Value::as_array)
        .cloned()
        .unwrap_or_default();
    let content = if blocks.is_empty() {
        text_content_or_none(text)
    } else {
        content_from_blocks(message, &blocks, text, options, output)
    };
    let content = if role == "user" {
        content.map(repeat_user_query_in_provider_content)
    } else {
        content
    };

    if content.is_some() {
        let content = content.unwrap_or_else(|| Value::String(String::new()));
        let merged = merge_user_content_with_transcript_citations(message, role, content);
        let merged = merge_user_content_with_page_citations(message, role, merged);
        let merged = merge_user_content_with_file_citations(message, role, merged);
        let inline_images = message
            .pointer("/metadata/inlineImages")
            .and_then(Value::as_array)
            .cloned()
            .unwrap_or_default();
        let file_images = message
            .pointer("/metadata/fileAttachments")
            .and_then(Value::as_array)
            .map(|items| {
                crate::native_backend::file_citations::inline_images_from_file_citations(items)
            })
            .unwrap_or_default();
        let (effective_inline_images, _) = effective_inline_images_for_user_turn(
            role,
            &inline_images,
            &file_images,
            text,
            all_messages,
            message_index,
        );
        let provider_inline_images = enrich_inline_images_for_provider(&effective_inline_images);
        let merged = merge_user_content_with_inline_images(role, merged, &provider_inline_images);
        let merged = if role == "user" && !provider_inline_images.is_empty() {
            if text_has_inline_image_markers(text) {
                expand_inline_image_markers_in_content(
                    merged,
                    &provider_inline_images,
                    options,
                    output,
                )
            } else {
                prepend_inline_images_vision_to_content(
                    merged,
                    &provider_inline_images,
                    options,
                    output,
                )
            }
        } else {
            merged
        };
        let provider_message = json!({
            "role": role,
            "content": merged,
        });
        projected.push(provider_message);
    }

    projected
}

fn merge_user_content_with_transcript_citations(
    message: &Value,
    role: &str,
    content: Value,
) -> Value {
    if role != "user" {
        return content;
    }
    let citations = message
        .pointer("/metadata/transcriptCitations")
        .and_then(Value::as_array)
        .filter(|items| !items.is_empty());
    let Some(citations) = citations else {
        return content;
    };
    let cite_blocks = citations
        .iter()
        .filter_map(format_transcript_cite_xml)
        .collect::<Vec<_>>()
        .join("\n");
    if cite_blocks.is_empty() {
        return content;
    }
    let user_text = match &content {
        Value::String(text) => text.clone(),
        Value::Array(parts) => parts
            .iter()
            .filter_map(|part| part.get("text").and_then(Value::as_str))
            .collect::<Vec<_>>()
            .join("\n"),
        _ => String::new(),
    };
    let merged = if user_text.trim().is_empty() {
        format!(
            "The user referenced prior transcript excerpts. Treat every <lyra-transcript-cite> block as a canonical anchor to a message that definitely occurred in this session, even if it is outside the current working context.\n\n{cite_blocks}"
        )
    } else {
        format!(
            "The user referenced prior transcript excerpts. Treat every <lyra-transcript-cite> block as a canonical anchor to a message that definitely occurred in this session, even if it is outside the current working context. When truncated=\"true\", call lyra_session_read_message with messageId (and offsets when present) before relying on the excerpt alone.\n\n{cite_blocks}\n\nUser message:\n{user_text}"
        )
    };
    Value::String(merged)
}

fn merge_user_content_with_inline_images(role: &str, content: Value, images: &[Value]) -> Value {
    if role != "user" || images.is_empty() {
        return content;
    }
    let image_blocks = images
        .iter()
        .filter_map(crate::native_backend::inline_images::format_inline_image_xml)
        .collect::<Vec<_>>()
        .join("\n");
    if image_blocks.is_empty() {
        return content;
    }
    let user_text = match &content {
        Value::String(text) => text.clone(),
        Value::Array(parts) => parts
            .iter()
            .filter_map(|part| part.get("text").and_then(Value::as_str))
            .collect::<Vec<_>>()
            .join("\n"),
        _ => String::new(),
    };
    let transcript_marker = "The user referenced prior transcript excerpts.";
    let page_marker = "The user referenced Workbench browser pages.";
    let image_anchor_hint = "Treat every <lyra-image-attach> block as a canonical inline image anchor for the member's inline image attachment. Attachment ids are session-local and are not artifact ids—never pass them to artifact_read. Use the source path on <lyra-image-attach>. Describe image content from vision input; describe transparency/alpha/format from lyra-image-attach traits (hasAlpha, transparentBackground, transparentPixelPercent, colorMode, visionComposited). When visionComposited=true, vision shows a white-backed composite for visibility—the original file at source may still be transparent.";
    let merged = if user_text.trim().is_empty() {
        format!("{image_anchor_hint}\n\n{image_blocks}")
    } else if user_text.contains(transcript_marker) || user_text.contains(page_marker) {
        format!("{user_text}\n\n{image_blocks}")
    } else {
        format!("{image_anchor_hint}\n\n{image_blocks}\n\nUser message:\n{user_text}")
    };
    Value::String(merged)
}

fn merge_user_content_with_page_citations(message: &Value, role: &str, content: Value) -> Value {
    if role != "user" {
        return content;
    }
    let citations = message
        .pointer("/metadata/pageCitations")
        .and_then(Value::as_array)
        .filter(|items| !items.is_empty());
    let Some(citations) = citations else {
        return content;
    };
    let cite_blocks = citations
        .iter()
        .filter_map(crate::native_backend::page_citations::format_page_cite_xml)
        .collect::<Vec<_>>()
        .join("\n");
    if cite_blocks.is_empty() {
        return content;
    }
    let user_text = match &content {
        Value::String(text) => text.clone(),
        Value::Array(parts) => parts
            .iter()
            .filter_map(|part| part.get("text").and_then(Value::as_str))
            .collect::<Vec<_>>()
            .join("\n"),
        _ => String::new(),
    };
    let user_text = crate::native_backend::page_citations::expand_page_cite_markers(
        &user_text,
        citations,
        crate::native_backend::page_citations::PageCiteMarkerMode::ModelUserText,
    );
    let transcript_marker = "The user referenced prior transcript excerpts.";
    let merged = if user_text.trim().is_empty() {
        format!(
            "The user referenced Workbench browser pages. Treat every <lyra-page-cite> as a compact pointer (tabId + pageUrl), not the full page. Look up more with workbench.read_tab / extract_tab_text / browser.read using tabId. For sourceKind=terminal-tab, pageUrl is lyra://terminal/{{terminalTabId}}; use terminal_read with that id. The block body is a small excerpt, and may include the filtered surface map (Now operable). truncated=true means the excerpt was cut — follow the ids.\n\n{cite_blocks}"
        )
    } else if user_text.contains(transcript_marker) {
        format!("{user_text}\n\n{cite_blocks}")
    } else {
        format!(
            "The user referenced Workbench browser pages. Treat every <lyra-page-cite> as a compact pointer (tabId + pageUrl), not the full page. Look up more with workbench.read_tab / extract_tab_text / browser.read using tabId. For sourceKind=terminal-tab, pageUrl is lyra://terminal/{{terminalTabId}}; use terminal_read with that id. The block body is a small excerpt, and may include the filtered surface map (Now operable). truncated=true means the excerpt was cut — follow the ids.\n\n{cite_blocks}\n\nUser message:\n{user_text}"
        )
    };
    Value::String(merged)
}

