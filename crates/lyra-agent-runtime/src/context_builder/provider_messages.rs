fn format_transcript_cite_xml(citation: &Value) -> Option<String> {
    let id = citation.get("id").and_then(Value::as_str)?;
    let message_id = citation.get("messageId").and_then(Value::as_str)?;
    let role = citation
        .get("role")
        .and_then(Value::as_str)
        .unwrap_or("assistant");
    let truncated = citation
        .get("truncated")
        .and_then(Value::as_bool)
        .unwrap_or(false);
    let block_id = citation
        .get("blockId")
        .and_then(Value::as_str)
        .map(|value| format!(" blockId=\"{value}\""))
        .unwrap_or_default();
    let start = citation
        .get("startOffset")
        .and_then(Value::as_u64)
        .map(|value| format!(" start=\"{value}\""))
        .unwrap_or_default();
    let end = citation
        .get("endOffset")
        .and_then(Value::as_u64)
        .map(|value| format!(" end=\"{value}\""))
        .unwrap_or_default();
    let quoted = citation
        .get("quotedText")
        .and_then(Value::as_str)
        .unwrap_or_default();
    Some(format!(
        "<lyra-transcript-cite id=\"{id}\" messageId=\"{message_id}\" role=\"{role}\" authentic=\"true\" truncated=\"{truncated}\"{block_id}{start}{end}>\n{quoted}\n</lyra-transcript-cite>"
    ))
}

fn text_content_or_none(text: &str) -> Option<Value> {
    (!text.trim().is_empty()).then(|| Value::String(text.to_string()))
}

/// ponytail: causal LMs cannot attend forward, so tokens at the start of a
/// query never see the question that arrives later (Xu et al. 2024 RE2;
/// Leviathan et al. 2025 Prompt Repetition). Repeat the user query once in
/// provider prefill. Session storage and the UI stay single-copy. Ceiling:
/// skip empty, already-doubled, and queries over 16_384 chars (prefill
/// latency). Upgrade: 3+ copies only if lookup-style tasks justify it (RE2
/// shows GSM8K drops past 2).
const MAX_QUERY_REPEAT_CHARS: usize = 16_384;

fn already_once_repeated(text: &str) -> bool {
    let Some((first, second)) = text.split_once("\n\n") else {
        return false;
    };
    !first.is_empty() && first == second
}

fn is_harness_omission_text(text: &str) -> bool {
    text.starts_with("[Image omitted:") || text.starts_with("[Media omitted:")
}

fn repeat_user_query(text: &str) -> String {
    if text.trim().is_empty() || already_once_repeated(text) {
        return text.to_string();
    }
    if text.chars().count() > MAX_QUERY_REPEAT_CHARS {
        return text.to_string();
    }
    format!("{text}\n\n{text}")
}

fn repeat_user_query_in_provider_content(content: Value) -> Value {
    match content {
        Value::String(text) => Value::String(repeat_user_query(&text)),
        Value::Array(mut parts) => {
            let index = parts.iter().position(|part| {
                part.get("type").and_then(Value::as_str) == Some("text")
                    && part
                        .get("text")
                        .and_then(Value::as_str)
                        .is_some_and(|text| {
                            !text.trim().is_empty() && !is_harness_omission_text(text)
                        })
            });
            if let Some(index) = index
                && let Some(text) = parts[index]
                    .get("text")
                    .and_then(Value::as_str)
                    .map(str::to_string)
            {
                parts[index]["text"] = Value::String(repeat_user_query(&text));
            }
            Value::Array(parts)
        }
        other => other,
    }
}

fn content_from_blocks(
    message: &Value,
    blocks: &[Value],
    fallback_text: &str,
    options: &ProviderContextOptions,
    output: &mut ProviderContext,
) -> Option<Value> {
    let mut parts = Vec::new();
    for block in blocks {
        match block.get("type").and_then(Value::as_str) {
            Some("text") => {
                if let Some(text) = block.get("text").and_then(Value::as_str)
                    && !text.trim().is_empty()
                {
                    parts.push(json!({ "type": "text", "text": text }));
                }
            }
            Some("image") => {
                if options.supports_image_input {
                    match provider_image_url(block) {
                        Some(url) => {
                            parts.push(json!({
                                "type": "image_url",
                                "image_url": { "url": url },
                            }));
                        }
                        None => {
                            let downgrade =
                                image_downgrade(message, block, "image_data_unavailable");
                            output.input_downgrades.push(downgrade.clone());
                            parts.push(json!({
                                "type": "text",
                                "text": format!(
                                    "[Image omitted: {}]",
                                    downgrade["reason"].as_str().unwrap_or("image unavailable")
                                )
                            }));
                        }
                    }
                } else {
                    let downgrade =
                        image_downgrade(message, block, "model_does_not_support_image_input");
                    output.input_downgrades.push(downgrade.clone());
                    parts.push(json!({
                        "type": "text",
                        "text": format!(
                            "[Image omitted: {}]",
                            downgrade["reason"].as_str().unwrap_or("image input unsupported")
                        )
                    }));
                }
            }
            Some("media") => {
                let media_type = block
                    .get("mediaType")
                    .or_else(|| block.get("media_type"))
                    .and_then(Value::as_str)
                    .unwrap_or_default();
                let model_supports_media = if media_type == "application/pdf" {
                    options.supports_pdf_input
                } else if media_type.starts_with("audio/") {
                    options.supports_audio_input
                } else if media_type.starts_with("video/") {
                    options.supports_video_input
                } else {
                    false
                };
                let supported = model_supports_media
                    && protocol_supports_media_type(options.protocol_id.as_deref(), media_type);
                if supported {
                    match provider_media_part(block, media_type) {
                        Some(part) => parts.push(part),
                        None => {
                            let downgrade = media_downgrade(
                                message,
                                block,
                                "media_data_unavailable_or_too_large",
                            );
                            output.input_downgrades.push(downgrade);
                            parts.push(json!({
                                "type": "text",
                                "text": format!("[Media omitted: {media_type} unavailable]")
                            }));
                        }
                    }
                } else {
                    let downgrade = media_downgrade(
                        message,
                        block,
                        "model_or_protocol_does_not_support_media_input",
                    );
                    output.input_downgrades.push(downgrade);
                    parts.push(json!({
                        "type": "text",
                        "text": format!("[Media omitted: {media_type} input unsupported]")
                    }));
                }
            }
            Some("tool") => {
                let tool_id = block
                    .get("toolId")
                    .or_else(|| block.get("tool_id"))
                    .and_then(Value::as_str)
                    .unwrap_or("tool");
                let evidence_ref = json!({
                    "kind": "tool_result_ref",
                    "toolId": tool_id,
                    "messageId": message.get("id").cloned().unwrap_or(Value::Null),
                });
                output.evidence_refs.push(evidence_ref);
                let summary = TOOL_OUTPUT_OMITTED_SUMMARY.to_string();
                let tool_budget = effective_tool_output_budget(options, message.get("id"));
                let (summary, maybe_ref) = if tool_budget == 0 {
                    (TOOL_OUTPUT_CLEARED_SUMMARY.to_string(), None)
                } else if summary.chars().count() > tool_budget {
                    let trimmed =
                        tool_activity_output_summary(&json!({ "content": summary }), tool_budget);
                    let evidence_ref = json!({
                        "kind": "truncated_tool_output",
                        "toolId": tool_id,
                        "messageId": message.get("id").cloned().unwrap_or(Value::Null),
                        "originalChars": summary.chars().count(),
                        "keptChars": tool_budget,
                    });
                    (trimmed, Some(evidence_ref))
                } else {
                    (summary, None)
                };
                if let Some(evidence_ref) = maybe_ref {
                    output.evidence_refs.push(evidence_ref);
                }
                parts.push(json!({
                    "type": "text",
                    "text": summary,
                }));
            }
            _ => {}
        }
    }

    if parts.is_empty() {
        return text_content_or_none(fallback_text);
    }

    if parts.len() == 1
        && let Some(text) = parts[0].get("text").and_then(Value::as_str)
    {
        return Some(Value::String(text.to_string()));
    }

    Some(Value::Array(parts))
}

fn provider_image_url(block: &Value) -> Option<String> {
    provider_image_url_from_value(block)
}

fn provider_media_part(block: &Value, media_type: &str) -> Option<Value> {
    let source = block.get("source").and_then(Value::as_str)?.trim();
    if source.is_empty() {
        return None;
    }
    let metadata = std::fs::metadata(source).ok()?;
    if !metadata.is_file() || metadata.len() > MAX_DIRECT_MEDIA_BYTES {
        return None;
    }
    let bytes = std::fs::read(source).ok()?;
    let filename = block
        .get("label")
        .and_then(Value::as_str)
        .filter(|value| !value.trim().is_empty())
        .or_else(|| {
            std::path::Path::new(source)
                .file_name()
                .and_then(|value| value.to_str())
        })
        .unwrap_or("attachment");
    Some(json!({
        "type": "input_media",
        "media_type": media_type,
        "data": BASE64_STANDARD.encode(bytes),
        "filename": filename,
    }))
}

fn media_downgrade(message: &Value, block: &Value, reason: &str) -> Value {
    json!({
        "kind": "media_input_downgrade",
        "reason": reason,
        "messageId": message.get("id").cloned().unwrap_or(Value::Null),
        "blockId": block.get("id").cloned().unwrap_or(Value::Null),
        "mediaType": block.get("mediaType").or_else(|| block.get("media_type")).cloned().unwrap_or(Value::Null),
        "label": block.get("label").cloned().unwrap_or(Value::Null),
        "source": block.get("source").cloned().unwrap_or(Value::Null),
    })
}

fn protocol_supports_media_type(protocol_id: Option<&str>, media_type: &str) -> bool {
    match protocol_id {
        Some("openai_chat_completions") => {
            matches!(media_type, "audio/mpeg" | "audio/wav" | "audio/x-wav")
        }
        Some("openai_responses" | "anthropic_messages") => media_type == "application/pdf",
        Some("gemini_generate_content" | "aws_bedrock_converse") => {
            media_type == "application/pdf"
                || media_type.starts_with("audio/")
                || media_type.starts_with("video/")
        }
        _ => false,
    }
}

